export type TranslationKey = keyof typeof TRANSLATIONS['en'];

export function getTranslation(key: TranslationKey, language: 'en' | 'fa'): string {
  const dict = TRANSLATIONS[language] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

export function translateStatus(status: string, language: 'en' | 'fa'): string {
  switch (status) {
    case 'active':
      return getTranslation('statusActive', language);
    case 'achieved':
      return getTranslation('statusAchieved', language);
    case 'paused':
      return getTranslation('statusPaused', language);
    case 'not_started':
      return getTranslation('statusNotStarted', language);
    case 'archived':
      return getTranslation('statusArchived', language);
    case 'todo':
      return getTranslation('statusTodo', language);
    case 'in_progress':
      return getTranslation('statusInProgress', language);
    case 'completed':
      return getTranslation('statusCompleted', language);
    case 'blocked':
      return getTranslation('statusBlocked', language);
    case 'cancelled':
      return getTranslation('statusCancelled', language);
    case 'pending':
      return getTranslation('statusPending', language);
    case 'processing':
      return getTranslation('statusProcessing', language);
    case 'in_flight':
      return getTranslation('statusInFlight', language);
    case 'synced':
      return getTranslation('statusSynced', language);
    case 'failed':
      return getTranslation('statusFailed', language);
    default:
      return status;
  }
}

